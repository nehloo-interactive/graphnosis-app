#!/usr/bin/env node
// Fails when the shipping-app version numbers disagree.
//
// SINGLE SOURCE OF TRUTH: apps/desktop/src-tauri/tauri.conf.json `version`.
// It already is the canon everywhere else — release.yml, build-linux.yml,
// release-mas.yml and sync-graphnosis-md.mjs all read `CANON` from it, and
// Tauri feeds it to `app.package_info().version`, which is what
// `getVersion()` returns and what sidecar.rs hands the sidecar as
// GRAPHNOSIS_APP_VERSION. Every other product number is a copy of it.
//
// Usage:
//   node scripts/check-versions.mjs            # check the four copies
//   node scripts/check-versions.mjs v1.31.0    # also require the tag to match
//
// Exit 0 = aligned, exit 1 = drift (with the offending files named).

import { readFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const read = (p) => readFileSync(join(ROOT, p), 'utf8');

const CANON_FILE = 'apps/desktop/src-tauri/tauri.conf.json';
const canon = JSON.parse(read(CANON_FILE)).version;

// Each entry: [file, extractor, why this number is user- or wire-visible].
const TRACKED = [
  [
    'apps/desktop/package.json',
    (s) => JSON.parse(s).version,
    'vite injects it as __APP_VERSION__ -> status-bar pill + lock-screen label',
  ],
  [
    'apps/desktop-sidecar/package.json',
    (s) => JSON.parse(s).version,
    'resolveSidecarVersion() fallback + docs-reingest gate; surfaces to Ghampus as graphnosis_app_version',
  ],
  [
    'apps/desktop/src-tauri/Cargo.toml',
    // [package] version — the first `version = "..."` at column 0.
    (s) => s.match(/^\[package\][\s\S]*?^version\s*=\s*"([^"]+)"/m)?.[1],
    'env!("CARGO_PKG_VERSION") -> the outbound User-Agent in remote.rs (goes over the network)',
  ],
  [
    'apps/desktop/src-tauri/Cargo.lock',
    (s) => s.match(/^name = "graphnosis-app"\nversion = "([^"]+)"$/m)?.[1],
    'must track Cargo.toml or the next cargo build rewrites it (and a --locked build fails)',
  ],
];

// Deliberately NOT tracked — these version independently, on purpose:
//   package.json (root)                        workspace manifest, private, never shipped
//   packages/graphnosis-app-core/package.json  private workspace lib, consumed as workspace:*
//   packages/graphnosis-mcp-relay/package.json published to npm on its own cadence
//   mcpb/manifest.json                         MCPB bundle, built + submitted separately
//   apps/docs/package.json                     website workspace manifest, never released
//   apps/vscode-extension/package.json         separate marketplace artifact
//   apps/docs .../FALLBACK_VERSION, public/_redirects
//                                              GENERATED by sync-graphnosis-md.mjs from the
//                                              latest PUBLISHED release; must LAG canon or
//                                              every /download/* link 404s during the build
//   GRAPHNOSIS.md line 3                       revision marker of that document, not the app
//   apps/desktop/src-tauri/swift/Info.plist    the biometric helper's own bundle
//   apps/desktop-sidecar/src/mcp-server.ts     MCP serverInfo, hardcoded '0.0.1' — see report

let failed = false;
console.log(`canonical version (${CANON_FILE}): ${canon}`);

for (const [file, extract, why] of TRACKED) {
  let found;
  try {
    found = extract(read(file));
  } catch (err) {
    console.error(`ERROR  ${file}: unreadable (${err.message})`);
    failed = true;
    continue;
  }
  if (!found) {
    console.error(`ERROR  ${file}: no version found — the extractor no longer matches this file`);
    failed = true;
  } else if (found !== canon) {
    console.error(`DRIFT  ${file}: ${found} but canon is ${canon}`);
    console.error(`       ^ ${why}`);
    failed = true;
  } else {
    console.log(`ok     ${file}: ${found}`);
  }
}

const tag = process.argv[2];
if (tag) {
  const tagVer = tag.replace(/^v/, '');
  if (tagVer !== canon) {
    console.error(`DRIFT  tag ${tag} does not match canon ${canon}`);
    failed = true;
  } else {
    console.log(`ok     tag ${tag}`);
  }
}

if (failed) {
  console.error('\nVersion consistency check FAILED.');
  process.exit(1);
}
console.log('\nAll tracked version declarations agree.');
